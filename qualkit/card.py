"""Assurance Card generator (spec AC-0.1, see ASSURANCE_CARDS.md).

An Assurance Card is a model card that carries MEASURED statistical
guarantees instead of prose: the conformal guarantee and its calibration
basis, the compression coverage forecast, prediction-set efficiency, fault
exposure, and a weight-integrity digest, plus the assumptions under which
the guarantee is valid. It is generated from a qualkit report, never
hand-written.
"""
AC_SPEC_VERSION = "AC-0.1"


def make_card(report, model_name, model_version="", dataset="", issued="",
              notes=""):
    """Build an Assurance Card dict from a qualkit report.run_all() result.

    `issued` is supplied by the caller (e.g. an ISO date) so cards are
    reproducible artifacts rather than timestamped side effects.
    """
    cf = report["coverage_forecast"]
    ss = report["setsize_acceptance"]
    ig = report["integrity"]
    card = {
        "assurance_card": AC_SPEC_VERSION,
        "model": {
            "name": model_name,
            "version": model_version,
            "dataset": dataset,
            "weights_sha256": ig["sha256"],
            "weight_bytes": ig["weight_bytes"],
        },
        "guarantee": {
            "type": "split_conformal_classification",
            "alpha": cf["alpha"],
            "target_coverage": cf["target_coverage"],
            "recalibrated_qhat": ss["recalibrated_qhat"],
            "valid_if": [
                "calibration data exchangeable with deployment data",
                "calibration performed on THIS artifact (weights_sha256 above)",
                "inputs pass the deployment gate the card was measured with",
            ],
        },
        "compression": {
            "tv_distance_vs_reference": cf["tv_distance"],
            "stale_calibration_coverage_floor": cf["forecast_coverage_floor"],
            "verdict": cf["verdict"],
        },
        "efficiency": {
            "mean_prediction_set_size": ss["mean_set_size"],
            "empty_set_rate": ss["empty_set_rate"],
            "acceptance_threshold": ss["threshold"],
            "verdict": ss["verdict"],
        },
        "fault_exposure": (
            {
                "storage_format": report["seu_probe"]["storage_format"],
                "single_flip_output_silent_fraction":
                    report["seu_probe"]["silent_fraction"],
                "note": "output-side monitoring cannot count faults; verify "
                        "the weights_sha256 digest periodically",
            } if "seu_probe" in report else {"measured": False}
        ),
        "issued": issued,
        "notes": notes,
        "generated_by": "qualkit",
    }
    return card


def card_markdown(card):
    m, g, c, e = (card["model"], card["guarantee"], card["compression"],
                  card["efficiency"])
    lines = [
        f"# Assurance Card ({card['assurance_card']})",
        "",
        f"**Model:** {m['name']} {m['version']}".rstrip(),
        f"**Dataset:** {m['dataset']}" if m["dataset"] else "",
        f"**Weights:** sha256 `{m['weights_sha256'][:16]}...` "
        f"({m['weight_bytes']:,} bytes)",
        "",
        "## Guarantee (measured, not asserted)",
        f"- Split conformal classification, alpha = {g['alpha']} "
        f"(target coverage {g['target_coverage']:.0%})",
        f"- Recalibrated threshold qhat = {g['recalibrated_qhat']:.4f}",
        "- Valid only if: " + "; ".join(g["valid_if"]),
        "",
        "## Compression",
        f"- TV distance vs reference model: {c['tv_distance_vs_reference']:.4f}",
        f"- Coverage floor if calibration were stale: "
        f"{c['stale_calibration_coverage_floor']:.3f}",
        f"- Verdict: **{c['verdict']}**",
        "",
        "## Efficiency",
        f"- Mean prediction-set size: {e['mean_prediction_set_size']:.2f} "
        f"(threshold {e['acceptance_threshold']}) - **{e['verdict']}**",
        f"- Refusal (empty-set) rate: {e['empty_set_rate']:.3f}",
        "",
    ]
    f = card["fault_exposure"]
    if f.get("measured", True):
        lines += [
            "## Fault exposure",
            f"- Storage format: {f['storage_format']}",
            f"- Single-flip output-silent fraction: "
            f"{f['single_flip_output_silent_fraction']:.2f}",
            f"- {f['note']}",
            "",
        ]
    if card["issued"]:
        lines.append(f"Issued: {card['issued']}")
    if card["notes"]:
        lines.append(f"Notes: {card['notes']}")
    lines.append("")
    lines.append("Generated by qualkit. Spec: ASSURANCE_CARDS.md "
                 "(github.com/ss1738/qualkit).")
    return "\n".join(x for x in lines if x is not None)
